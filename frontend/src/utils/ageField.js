/**
 * 「分年龄人口」字段判定 —— **单一入口**（v1.13.228）
 *
 * 背景：高精度人口（250m 网格）带 **24 个**分年龄字段
 *   （男0_18 / 男19_24 / … / 男70以上；女0_18 / … / 女70以上），
 *   而「人口分布分析」结果面板是**逐字段一行**渲染的 ⇒ 连同其它字段共 35 行，
 *   纵向过长导致弹窗显示不全。⇒ 该面板**不展示**分年龄字段。
 *
 * 🔴 判定只看「性别字 + 数字」前缀：
 *   · `男0_18` / `男19_24` / `女70以上` ⇒ 判定为分年龄（后接**数字**）
 *   · `男性人数` / `女性人数`          ⇒ **不是**分年龄（后接「性」）—— 它们是**总量**，必须保留
 *
 * ⚠️ 改本判据前想清楚两侧后果：判漏 ⇒ 年龄行又回到面板；判宽 ⇒ 连「男性人数」一起误杀。
 * 回归钉子：`backend/tests/hdPopulationDistribution.test.js`（⑧ 行为断言，直接 import 本函数跑真实字段）
 * ⚠️ 本模块**不得**静态引用 `@/router` 等入口 chunk 内模块（会反向提升首屏依赖，见 214 立档）。
 */

/** 分年龄字段：性别字 + 数字开头（如 男0_18 / 女70以上） */
const AGE_GROUP_RE = /^[男女]\d/

/**
 * @param {*} name 字段名
 * @returns {boolean} 是否为「分年龄人口」字段（非字符串/空值一律 false）
 */
export function isAgeGroupField(name) {
  return AGE_GROUP_RE.test(String(name == null ? '' : name))
}

export default isAgeGroupField
