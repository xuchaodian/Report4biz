/** 全部 FAQ（供快捷问句等场景使用） */
export function listFaqs() {
  return FAQS.map(f => ({
    id: f.id,
    title: f.title,
    question: FAQ_QUESTIONS[f.id] || `怎么${f.title.replace(/（.*?）/, '')}？`
  }))
}
